const dir = path.join(process.cwd(), "src", "messages");

// en.json holds the canonical block — validate completeness, don't rewrite it.
const enJson = JSON.parse(fs.readFileSync(path.join(dir, "en.json"), "utf8"));
for (const k of KEYS) {
  if (typeof enJson.admin?.websiteEditor?.[k] !== "string") {
    throw new Error(`en.json admin.websiteEditor.${k} missing — add it before splicing`);
  }
}

let changed = 0;
for (const loc of SUPPORTED_LOCALES) {
  if (loc === "en") continue;
  const pack = TRANSLATIONS[loc];
  if (!pack) throw new Error(`No translation pack for locale "${loc}"`);
  for (const k of KEYS) {
    if (typeof pack[k] !== "string" || !pack[k].trim()) {
      throw new Error(`Translation pack "${loc}" missing/empty key "${k}"`);
    }
  }

  const file = path.join(dir, `${loc}.json`);
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!json.admin || typeof json.admin !== "object") {
    throw new Error(`${loc}.json missing top-level "admin" block`);
  }
  if (!json.admin.websiteEditor || typeof json.admin.websiteEditor !== "object") {
    throw new Error(`${loc}.json missing "admin.websiteEditor" block`);
  }
  for (const k of KEYS) {
    json.admin.websiteEditor[k] = pack[k];
  }
  fs.writeFileSync(file, JSON.stringify(json, null, 2) + "\n", "utf8");
  changed++;
}

console.log(`Spliced ${KEYS.length} keys into ${changed} locale files.`);
