const MESSAGES_DIR = path.join(process.cwd(), "src", "messages");

/** ICU placeholder names outside plural/select branches. */
function placeholderArgs(s: string): Set<string> {
  let prev: string;
  let cur = s;
  const branch = /\b(?:zero|one|two|few|many|other|=\d+)\s*\{[^{}]*\}/g;
  do {
    prev = cur;
    cur = cur.replace(branch, " ");
  } while (cur !== prev);
  const args = new Set<string>();
  for (const m of cur.matchAll(/\{\s*([a-zA-Z0-9_]+)\s*(?:,|\})/g)) args.add(m[1]);
  return args;
}
const sameSet = (a: Set<string>, b: Set<string>) => a.size === b.size && [...a].every((x) => b.has(x));

/** "topics.other" → nested object. */
function unflatten(flat: Record<string, string>): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(flat)) {
    const parts = k.split(".");
    let cur = out;
    for (let i = 0; i < parts.length - 1; i++) {
      cur[parts[i]] = (cur[parts[i]] as Record<string, unknown>) ?? {};
      cur = cur[parts[i]] as Record<string, unknown>;
    }
    cur[parts[parts.length - 1]] = v;
  }
  return out;
}

let changed = 0;
for (const locale of SUPPORTED_LOCALES) {
  const tr = T[locale];
  if (!tr) {
    console.error(`✗ ${locale}: NO TRANSLATION — refusing to write an English fallback.`);
    process.exitCode = 1;
    continue;
  }
  let bad = false;
  for (const k of KEYS) {
    if (typeof tr[k] !== "string" || !tr[k].trim()) {
      console.error(`✗ ${locale}: missing key ${k}`);
      bad = true;
      continue;
    }
    if (!sameSet(placeholderArgs(T.en[k]), placeholderArgs(tr[k]))) {
      console.error(`✗ ${locale}: ${k} placeholder mismatch (${[...placeholderArgs(tr[k])].join(",")} vs ${[...placeholderArgs(T.en[k])].join(",")})`);
      bad = true;
    }
    if (!/Nabil|Fee Free/.test(T.en[k])) continue;
    // Brand words stay untranslated wherever English uses them.
    if (/Nabil/.test(T.en[k]) && !/Nabil/.test(tr[k])) {
      console.error(`✗ ${locale}: ${k} lost the brand word "Nabil"`);
      bad = true;
    }
    if (/Fee Free/.test(T.en[k]) && !/Fee.Free/.test(tr[k])) {
      console.error(`✗ ${locale}: ${k} lost the brand word "Fee Free"`);
      bad = true;
    }
  }
  const extra = Object.keys(tr).filter((k) => !(KEYS as readonly string[]).includes(k));
  if (extra.length) {
    console.error(`✗ ${locale}: extra keys ${extra.join(",")}`);
    bad = true;
  }
  if (bad) {
    process.exitCode = 1;
    continue;
  }

  const file = path.join(MESSAGES_DIR, `${locale}.json`);
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  const detail = json?.admin?.phoneOrderingPage?.callDetail;
  if (!detail) {
    console.error(`✗ ${locale}: admin.phoneOrderingPage.callDetail missing`);
    process.exitCode = 1;
    continue;
  }
  const flat: Record<string, string> = {};
  for (const k of KEYS) flat[k] = tr[k];
  detail.report = unflatten(flat);
  fs.writeFileSync(file, JSON.stringify(json, null, 2) + "\n", "utf8");
  changed++;
}

