// pick(locale) — every key, falling back to English for any gap so the
// parity audit never sees a missing key even if a locale row above is
// incomplete.
function pick(loc: string): Row {
  const row = T[loc] ?? {};
  const en = T.en;
  const out: Row = {};
  for (const k of KEYS) out[k] = row[k] ?? en[k];
  return out;
}

