/**
 * i18n patch for the customer SMS / branded-app PUSH bodies (Luigi 2026-08-11).
 *
 * `buildCustomerSms()` in src/lib/notifications.ts built every customer text
 * from hardcoded English template literals — no t(), no keys — and the same
 * builder feeds branded-app push notifications. It was only ever harmless
 * because no restaurant had bought the `customer_sms` or `app_store_listing`
 * add-on yet. These keys give every shape a voice in all 38 locales:
 *
 *   sms.orderReceived         — placement, restaurant still has to accept
 *   sms.orderConfirmed(Eta)   — auto-accepted at placement (no 2nd text coming)
 *   sms.accepted(Eta)         — kitchen accepted
 *   sms.ready / sms.completed
 *   sms.missed                — auto-rejected on timeout (never blame the guest)
 *   sms.rejected(Reason) / sms.cancelled(Reason)
 *   sms.delayed(Eta)          — kitchen pushed the ready time back
 *   sms.reservationRequested / Confirmed / Declined / Missed / Cancelled
 *
 * The `Eta` / `Reason` variants exist because gluing " — ready ~19:30" onto a
 * translated sentence only works in English: clause order and punctuation move
 * per language, so each shape gets its own whole sentence.
 *
 * THREE rules the wording follows, and any new key must too:
 *
 *  1. SINGLE SEGMENT. Bodies stay short enough that restaurantName + text fits
 *     one SMS. src/lib/sms-i18n.test.ts enforces the ceiling across all 38.
 *  2. GSM-7 PUNCTUATION ONLY: plain "-" (never an em dash), straight quotes, no
 *     "~". One non-GSM character flips the WHOLE message to UCS-2, which halves
 *     the segment size from 160 to 70 chars and doubles what Luigi pays Twilio.
 *     (Locales whose alphabet is non-GSM anyway — el/bg/ru/uk/th/zh/ja/ko/ar/he/hi
 *     and the accented Latin ones — are UCS-2 regardless; the rule still costs
 *     them nothing.)
 *  3. Reuse each locale's EXISTING email vocabulary (email.orderStatus.*,
 *     email.reservationConfirmed.*) so a customer never reads the order
 *     "confirmed" two different ways across email and text. German is the
 *     formal "Sie"; Serbian is Latin ekavian; pt vs pt-BR keep their
 *     encomenda/pedido split; Hungarian keeps its "#{n}. rendelés" ordinal.
 *
 *   npx tsx scripts/i18n-add-sms-keys.ts
 */
