/** Map BCP-47 or locale code to our locale key (e.g. "en-US" → "en", "pt-BR" → "pt-BR"). */
export function resolveVoiceLocale(lang: string | null | undefined): string {
  if (!lang) return "en";
  if (P[lang]) return lang;
  const base = lang.split(/[-_]/)[0].toLowerCase();
  if (P[base]) return base;
  return "en";
}

export function voicePhrase(lang: string | null | undefined, key: PhraseKey): string {
  return (P[resolveVoiceLocale(lang)] ?? P.en)[key];
}

export function voiceFillers(lang: string | null | undefined, type: "fillers" | "thinkingFillers" | "stillThereFillers"): string[] {
  return (P[resolveVoiceLocale(lang)] ?? P.en)[type];
}
